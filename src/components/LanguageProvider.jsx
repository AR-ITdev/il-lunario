export function LanguageProvider({ children }) {
  const [locale, setLocale] = useState("it");

  useEffect(() => {
    const savedLocale = window.localStorage.getItem("il-lunario-locale");
    if (savedLocale === "en" || savedLocale === "fr" || savedLocale === "it") {
      setLocale(savedLocale);
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  function changeLocale(nextLocale) {
    if (!messages[nextLocale]) return;
    window.localStorage.setItem("il-lunario-locale", nextLocale);
    setLocale(nextLocale);
  }

  const value = useMemo(() => ({
    locale,
    setLocale: changeLocale,
    t: (key) => messages[locale][key] || messages.it[key] || key,
    categoryLabel: (category) => {
      const key = categoryKeys[category];
      return key ? messages[locale][`category.${key}`] : category;
    },
    categoryDescription: (slug) =>
      categorySlugs[slug] ? messages[locale][`categoryDesc.${categorySlugs[slug]}`] : "",
    productText: (slug, shortDescription, description) => {
      const translated = productTranslations[locale]?.[slug];
      return translated
        ? { shortDescription: translated[0], description: translated[1] }
        : { shortDescription, description };
    },
  }), [locale]);

  return <languageContext.Provider value={value}>{children}</languageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(languageContext);
  if (!context) throw new Error("useLanguage must be used within LanguageProvider.");
  return context;
}
